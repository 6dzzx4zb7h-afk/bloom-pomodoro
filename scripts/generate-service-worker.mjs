import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, extname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_OUT_DIR = resolve(ROOT, 'dist');
const CACHE_PREFIX = 'bloom-shell-';
// PLAN 8.15: v2 caches the HTML shell through its canonical root URL so every
// navigation uses one stable cache key across static web servers.
const POLICY_VERSION = 'precache-policy-v2';

const PRECACHE_EXTENSIONS = new Set([
  '.avif',
  '.css',
  '.html',
  '.ico',
  '.js',
  '.json',
  '.png',
  '.svg',
  '.ttf',
  '.webmanifest',
  '.webp',
  '.woff',
  '.woff2',
]);

// These namespaces are reserved for optional network capabilities. Even if a
// future build happens to emit a similarly named file, it must remain outside
// Bloom's app-shell cache.
const NETWORK_ONLY_ROOTS = ['/api', '/auth', '/oauth', '/.well-known'];

function toPosixPath(path) {
  return path.split(sep).join('/');
}

function isNetworkOnlyPath(pathname) {
  return NETWORK_ONLY_ROOTS.some(
    (root) => pathname === root || pathname.startsWith(`${root}/`),
  );
}

export function shouldPrecache(relativePath) {
  const normalized = toPosixPath(relativePath);
  const basename = normalized.split('/').at(-1) ?? '';
  const pathname = `/${normalized}`;

  if (!normalized || basename === 'sw.js' || basename.startsWith('_') || basename.startsWith('.')) {
    return false;
  }

  return PRECACHE_EXTENSIONS.has(extname(basename).toLowerCase()) && !isNetworkOnlyPath(pathname);
}

async function walkFiles(root, current = root) {
  const entries = await readdir(current, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const absolute = join(current, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await walkFiles(root, absolute)));
    } else if (entry.isFile()) {
      files.push(toPosixPath(relative(root, absolute)));
    }
  }

  return files;
}

export async function collectPrecacheFiles(outDir = DEFAULT_OUT_DIR) {
  const files = await walkFiles(outDir);
  return files.filter(shouldPrecache).sort();
}

export async function computeBuildHash(outDir, files) {
  const hash = createHash('sha256');
  hash.update(POLICY_VERSION);

  for (const file of files) {
    hash.update('\0');
    hash.update(file);
    hash.update('\0');
    hash.update(await readFile(resolve(outDir, file)));
  }

  return hash.digest('hex').slice(0, 16);
}

export function renderServiceWorker(buildHash, files) {
  if (!files.includes('index.html')) {
    throw new Error('Cannot generate Bloom service worker without dist/index.html');
  }

  const urls = files.map((file) => (file === 'index.html' ? '/' : `/${file}`));

  return `/* Generated by scripts/generate-service-worker.mjs. Do not edit. */
const CACHE_PREFIX = ${JSON.stringify(CACHE_PREFIX)};
const CACHE_NAME = ${JSON.stringify(`${CACHE_PREFIX}${buildHash}`)};
const APP_SHELL = '/';
const PRECACHE_URLS = ${JSON.stringify(urls, null, 2)};
const PRECACHE_PATHS = new Set(PRECACHE_URLS);
const NETWORK_ONLY_ROOTS = ${JSON.stringify(NETWORK_ONLY_ROOTS)};

function isNetworkOnlyPath(pathname) {
  return NETWORK_ONLY_ROOTS.some(
    (root) => pathname === root || pathname.startsWith(root + '/'),
  );
}

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    const requests = PRECACHE_URLS.map(
      (url) => new Request(new URL(url, self.location.origin), {
        cache: 'reload',
        credentials: 'same-origin',
      }),
    );
    await cache.addAll(requests);
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const cacheNames = await caches.keys();
    await Promise.all(
      cacheNames
        .filter((name) => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME)
        .map((name) => caches.delete(name)),
    );
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin || isNetworkOnlyPath(url.pathname)) return;

  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE_NAME);
      const cachedShell = await cache.match(APP_SHELL);
      return cachedShell ?? fetch(request);
    })());
    return;
  }

  if (!PRECACHE_PATHS.has(url.pathname)) return;

  event.respondWith((async () => {
    const cache = await caches.open(CACHE_NAME);
    const cachedAsset = await cache.match(url.pathname, { ignoreSearch: true });
    return cachedAsset ?? fetch(request);
  })());
});
`;
}

export async function generateServiceWorker(outDir = DEFAULT_OUT_DIR) {
  const files = await collectPrecacheFiles(outDir);
  const buildHash = await computeBuildHash(outDir, files);
  const source = renderServiceWorker(buildHash, files);
  const outputPath = resolve(outDir, 'sw.js');
  await writeFile(outputPath, source, 'utf8');
  return { buildHash, files, outputPath };
}

const invokedPath = process.argv[1] ? resolve(process.argv[1]) : '';
if (invokedPath === fileURLToPath(import.meta.url)) {
  generateServiceWorker()
    .then(({ buildHash, files }) => {
      console.log(`Generated Bloom app-shell service worker ${buildHash} (${files.length} files).`);
    })
    .catch((error) => {
      console.error(error);
      process.exitCode = 1;
    });
}
